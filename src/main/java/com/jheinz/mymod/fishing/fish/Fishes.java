package com.jheinz.mymod.fishing.fish;

import java.util.List;
import java.util.function.Consumer;
import java.util.function.Function;

import net.fabricmc.fabric.api.creativetab.v1.CreativeModeTabEvents;

import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.sounds.SoundEvents;
import net.minecraft.sounds.SoundSource;
import net.minecraft.world.effect.MobEffectInstance;
import net.minecraft.world.effect.MobEffects;
import net.minecraft.world.food.FoodProperties;
import net.minecraft.world.item.CreativeModeTabs;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.Items;
import net.minecraft.world.item.Rarity;
import net.minecraft.world.item.component.Consumable;
import net.minecraft.world.item.component.Consumables;
import net.minecraft.world.item.consume_effects.ApplyStatusEffectsConsumeEffect;
import net.minecraft.world.level.storage.loot.providers.number.ints.ContextIntProviders;

import com.jheinz.mymod.MyMod;
import com.jheinz.mymod.uranium.Radiation;

/**
 * The fish the fishing system lands: each is an item here, and a species file (data/mymod/fishing_species) says where
 * and how hard it's caught. Models, textures, species files and recipes are generated by tools/gen_fish.py.
 *
 * <p>Most are food, and the common ones cook (furnace, smoker or campfire) into something better. The odd ones feed
 * the mod's other systems:
 * <ul>
 * <li>Oily fish (mackerel, bog eel, and three bottles' worth from a magma eel) render into Fish Oil: it burns like
 * coal, and four bottles and an empty canister make a canister of crude for the Refinery's kerosene, rocket fuel and
 * napalm.
 * <li>The Glowing Mutant Carp, from the water down among the uranium, glows and irradiates whoever eats it.
 * <li>The Sculk Gulper's belly is full of swallowed experience; it also crafts into sculk.
 * <li>An anglerfish lights ink (glow ink sacs), a pixie minnow crumbles to Fae Dust, an ice char freezes packed ice
 * into blue ice for the Froststeel quench, three ghoulfish and a soul block give up a Soul Charge for soul steel, and an
 * ember puffer dries to blaze powder for rocket fuel.
 * </ul>
 */
public final class Fishes {
	// --- Rivers and lakes ---------------------------------------------------------------------------------------
	public static final Item BROOK_TROUT = food("brook_trout", 2, 0.1f);
	public static final Item COOKED_BROOK_TROUT = food("cooked_brook_trout", 6, 0.8f);
	public static final Item MUD_CATFISH = food("mud_catfish", 2, 0.1f);
	public static final Item COOKED_MUD_CATFISH = food("cooked_mud_catfish", 6, 0.7f);
	public static final Item PIKE = food("pike", 2, 0.1f);
	public static final Item COOKED_PIKE = food("cooked_pike", 6, 0.8f);

	// --- Ocean ----------------------------------------------------------------------------------------------------
	public static final Item MACKEREL = food("mackerel", 2, 0.1f);
	public static final Item COOKED_MACKEREL = food("cooked_mackerel", 5, 0.6f);
	public static final Item SWORDFISH = food("swordfish", 3, 0.2f, Rarity.UNCOMMON);
	public static final Item SWORDFISH_STEAK = food("swordfish_steak", 8, 0.8f, Rarity.UNCOMMON);
	/** Its lure still glows: a little night vision. */
	public static final Item ANGLERFISH = food("anglerfish", 2, 0.2f, effects(new MobEffectInstance(MobEffects.NIGHT_VISION, 300)));
	public static final Item GLOWFIN_TETRA = food("glowfin_tetra", 1, 0.1f);
	public static final Item PARROTFISH = food("parrotfish", 2, 0.1f);
	public static final Item COOKED_PARROTFISH = food("cooked_parrotfish", 5, 0.6f);

	// --- Cold, swamps and caves -----------------------------------------------------------------------------------
	public static final Item ICE_CHAR = food("ice_char", 2, 0.1f);
	public static final Item COOKED_ICE_CHAR = food("cooked_ice_char", 6, 0.8f);
	public static final Item BOG_EEL = food("bog_eel", 2, 0.1f, effects(0.3f, new MobEffectInstance(MobEffects.HUNGER, 300)));
	public static final Item COOKED_BOG_EEL = food("cooked_bog_eel", 6, 0.6f);
	/** Raw, the blind thing sometimes passes its blindness on. */
	public static final Item CAVE_BLINDFISH = food("cave_blindfish", 1, 0.1f, effects(0.3f, new MobEffectInstance(MobEffects.BLINDNESS, 100)));
	public static final Item COOKED_CAVE_BLINDFISH = food("cooked_cave_blindfish", 4, 0.6f);
	/** A belly full of swallowed experience, and a moment of the deep dark's Darkness. */
	public static final Item SCULK_GULPER = special("sculk_gulper", 2, 0.1f, Rarity.UNCOMMON,
			effects(new MobEffectInstance(MobEffects.DARKNESS, 80)), Fishes::releaseExperience);

	// --- The Feywild ----------------------------------------------------------------------------------------------
	public static final Item PIXIE_MINNOW = food("pixie_minnow", 1, 0.2f, effects(new MobEffectInstance(MobEffects.SLOW_FALLING, 200)));
	public static final Item MOONSCALE_KOI = food("moonscale_koi", 4, 0.8f, Rarity.RARE,
			effects(new MobEffectInstance(MobEffects.NIGHT_VISION, 1200), new MobEffectInstance(MobEffects.REGENERATION, 100)));

	// --- Lava -----------------------------------------------------------------------------------------------------
	public static final Item MAGMA_EEL = food("magma_eel", 3, 0.3f, Rarity.UNCOMMON,
			effects(new MobEffectInstance(MobEffects.FIRE_RESISTANCE, 600)));
	/** As poisonous as a pufferfish, and still smouldering. */
	public static final Item EMBER_PUFFER = special("ember_puffer", 1, 0.1f, Rarity.UNCOMMON, Consumables.PUFFERFISH,
			player -> player.igniteForSeconds(3.0f));

	// --- The invasion ---------------------------------------------------------------------------------------------
	/** Two heads, and it glows: whoever eats it glows too and takes a dose of radiation (Hazmat Suit or not). */
	public static final Item GLOWING_MUTANT_CARP = special("glowing_mutant_carp", 3, 0.2f, Rarity.UNCOMMON,
			effects(new MobEffectInstance(MobEffects.GLOWING, 600)), player -> Radiation.irradiate(player, Radiation.MINING_DOSE));
	/** Caught under a clear night sky: luck (for fishing, too) and starlight to see by. */
	public static final Item STARLIT_GAR = food("starlit_gar", 4, 0.6f, Rarity.RARE,
			effects(new MobEffectInstance(MobEffects.LUCK, 6000), new MobEffectInstance(MobEffects.NIGHT_VISION, 1800)));
	public static final Item ABYSSAL_SQUIDLING = food("abyssal_squidling", 3, 0.4f, Rarity.RARE,
			effects(new MobEffectInstance(MobEffects.WATER_BREATHING, 1200), new MobEffectInstance(MobEffects.DOLPHINS_GRACE, 600),
					new MobEffectInstance(MobEffects.NAUSEA, 100)));
	/** Cursed flesh: hunger and a touch of wither. Better wrung out for its soul. */
	public static final Item GHOULFISH = food("ghoulfish", 2, 0.1f, Rarity.UNCOMMON,
			effects(new MobEffectInstance(MobEffects.HUNGER, 600), new MobEffectInstance(MobEffects.WITHER, 100)));

	// --- Not fish -------------------------------------------------------------------------------------------------
	public static final Item OLD_BOOT = register("old_boot", Item::new, new Item.Properties().stacksTo(16));
	/** Burns like coal and leaves its bottle behind; four make a canister of crude for the Refinery. */
	public static final Item FISH_OIL = register("fish_oil", Item::new, new Item.Properties().stacksTo(16)
			.craftRemainder(Items.GLASS_BOTTLE).cookingFuel(ContextIntProviders.COOKING_TIME_COAL));

	/** Food & Drinks, after vanilla's fish: each raw fish followed by its cooked form. */
	private static final List<Item> FOOD_TAB = List.of(BROOK_TROUT, COOKED_BROOK_TROUT, MUD_CATFISH, COOKED_MUD_CATFISH, PIKE, COOKED_PIKE,
			MACKEREL, COOKED_MACKEREL, SWORDFISH, SWORDFISH_STEAK, ANGLERFISH, GLOWFIN_TETRA, PARROTFISH, COOKED_PARROTFISH, ICE_CHAR,
			COOKED_ICE_CHAR, BOG_EEL, COOKED_BOG_EEL, CAVE_BLINDFISH, COOKED_CAVE_BLINDFISH, SCULK_GULPER, PIXIE_MINNOW, MOONSCALE_KOI,
			MAGMA_EEL, EMBER_PUFFER, GLOWING_MUTANT_CARP, STARLIT_GAR, ABYSSAL_SQUIDLING, GHOULFISH);

	/** Experience in a Sculk Gulper's belly. */
	private static final int GULPER_EXPERIENCE = 20;

	private Fishes() {
	}

	private static void releaseExperience(ServerPlayer player) {
		player.giveExperiencePoints(GULPER_EXPERIENCE);
		player.level().playSound(null, player.getX(), player.getY(), player.getZ(), SoundEvents.EXPERIENCE_ORB_PICKUP, SoundSource.PLAYERS,
				0.6f, 0.8f);
	}

	private static Consumable effects(MobEffectInstance... effects) {
		return Consumables.defaultFood().onConsume(new ApplyStatusEffectsConsumeEffect(List.of(effects))).build();
	}

	private static Consumable effects(float chance, MobEffectInstance effect) {
		return Consumables.defaultFood().onConsume(new ApplyStatusEffectsConsumeEffect(effect, chance)).build();
	}

	private static Item.Properties properties(int nutrition, float saturation, Rarity rarity, Consumable consumable) {
		return new Item.Properties().rarity(rarity)
				.food(new FoodProperties.Builder().nutrition(nutrition).saturationModifier(saturation).build(), consumable);
	}

	private static Item food(String name, int nutrition, float saturation) {
		return food(name, nutrition, saturation, Rarity.COMMON, Consumables.DEFAULT_FOOD);
	}

	private static Item food(String name, int nutrition, float saturation, Rarity rarity) {
		return food(name, nutrition, saturation, rarity, Consumables.DEFAULT_FOOD);
	}

	private static Item food(String name, int nutrition, float saturation, Consumable consumable) {
		return food(name, nutrition, saturation, Rarity.COMMON, consumable);
	}

	private static Item food(String name, int nutrition, float saturation, Rarity rarity, Consumable consumable) {
		return register(name, Item::new, properties(nutrition, saturation, rarity, consumable));
	}

	private static Item special(String name, int nutrition, float saturation, Rarity rarity, Consumable consumable,
			Consumer<ServerPlayer> onEaten) {
		return register(name, properties -> new FishItem(properties, onEaten), properties(nutrition, saturation, rarity, consumable));
	}

	private static Item register(String name, Function<Item.Properties, Item> factory, Item.Properties properties) {
		ResourceKey<Item> key = ResourceKey.create(Registries.ITEM, MyMod.id(name));
		return Registry.register(BuiltInRegistries.ITEM, key, factory.apply(properties.setId(key)));
	}

	public static void initialize() {
		CreativeModeTabEvents.modifyOutputEvent(CreativeModeTabs.FOOD_AND_DRINKS)
				.register(output -> output.insertAfter(Items.PUFFERFISH, FOOD_TAB.toArray(Item[]::new)));
		CreativeModeTabEvents.modifyOutputEvent(CreativeModeTabs.INGREDIENTS).register(output -> {
			output.insertAfter(Items.GLOW_INK_SAC, FISH_OIL);
			output.insertAfter(Items.LEATHER, OLD_BOOT);
		});
	}
}
