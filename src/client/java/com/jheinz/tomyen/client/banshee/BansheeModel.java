	@Override
	public void setupAnim(BansheeRenderState state) {
		super.setupAnim(state);
		float age = state.ageInTicks;
		float speed = Math.min(1.0f, state.walkAnimationSpeed);
		float death = state.deathProgress;
		float alive = 1.0f - death;
		float flare = Math.max(state.windup, state.scream);
		float banish = state.banished ? death : 0.0f;
		float fade = state.banished ? 0.0f : death;
		float reach = Mth.sin(state.attackAnim * Mth.PI);
		float tremble = state.scream * Mth.sin(age * 2.7f);

		// Drifting: a slow bob and sway, leaning into her movement; rising and rearing back to wail.
		body.xRot += 0.25f * speed + 0.12f * reach - 0.15f * flare + 0.35f * fade - 0.4f * banish;
		body.zRot += 0.04f * Mth.sin(age * 0.05f) * alive + 0.03f * tremble;
		body.x += 0.25f * tremble;
		body.y += Mth.sin(age * 0.08f) * alive - 2.0f * flare + 5.0f * fade - 6.0f * banish;
		neck.xRot += -0.1f * flare + 0.5f * fade - 0.3f * banish;
		// She looks where she's looking, until she wails (straight at her quarry, which the body already faces).
		float look = alive * (1.0f - flare);
		head.yRot += Mth.clamp(state.yRot, -60.0f, 60.0f) * Mth.DEG_TO_RAD * look;
		head.xRot += state.xRot * Mth.DEG_TO_RAD * 0.6f * look + 0.1f * reach - 0.2f * flare + 0.4f * fade - 0.4f * banish;
		head.zRot += 0.08f * Mth.sin(age * 0.045f) * alive;

		// The jaw hangs slack, trembling; it drops open through the wind-up and unhinges for the scream.
		float gape = Math.max(0.55f * state.windup + 0.75f * state.scream, banish);
		float unhinge = Math.max(state.scream, banish);
		jaw.xRot += 0.04f * Mth.sin(age * 0.11f) * alive + gape + 0.1f * tremble;
		jaw.y += 1.3f * unhinge;
		jaw.z += 0.3f * state.scream;
		jaw.yScale = 1.0f + 0.35f * unhinge;

		for (int s = 0; s < 2; s++) {
			// -1 for her right, +1 for her left, as in the generator.
			float side = s == 0 ? -1.0f : 1.0f;
			float phase = s == 0 ? 0.0f : 1.9f;
			// Hair: drifting as if under water, streaming behind as she moves, flaring out wide to wail.
			hair[s].xRot += 0.06f * Mth.sin(age * 0.06f + phase) + 0.3f * speed + 0.5f * flare + 0.4f * banish;
			hair[s].zRot += -side * (0.05f * Mth.sin(age * 0.07f + phase) + 0.85f * flare + 0.12f * tremble + 0.6f * banish - 0.08f * fade);
			hairLow[s].xRot += 0.08f * Mth.sin(age * 0.06f + phase - 0.9f) + 0.2f * speed + 0.25f * flare;
			hairLow[s].zRot += -side * (0.06f * Mth.sin(age * 0.08f + phase - 0.7f) + 0.35f * flare + 0.15f * tremble);
			// Arms: reaching forward, swaying; thrust out to touch; flung wide and back to wail; up when banished.
			arms[s].xRot += 0.1f * Mth.sin(age * 0.07f + phase) * alive - 0.45f * reach + 0.85f * flare + 1.0f * fade - 1.6f * banish;
			arms[s].yRot += side * 0.25f * reach - side * 0.4f * flare;
			arms[s].zRot += -side * (0.03f * Mth.sin(age * 0.09f + phase) + 1.0f * flare + 0.1f * tremble + 0.6f * banish);
			forearms[s].xRot += 0.1f * Mth.sin(age * 0.07f + phase + 0.8f) * alive + 0.15f * reach - 0.2f * flare + 0.2f * fade;
			hands[s].xRot += 0.1f * Mth.sin(age * 0.09f + phase) * alive - 0.25f * flare;
			fingers[s].xRot += 0.12f * Mth.sin(age * 0.1f + phase) * alive - 0.45f * reach - 0.5f * flare + 0.3f * fade;
		}
		hairBack.xRot += 0.05f * Mth.sin(age * 0.05f) + 0.45f * speed + 1.0f * flare + 0.15f * tremble + 0.8f * banish;
		hairBackLow.xRot += 0.07f * Mth.sin(age * 0.05f - 0.8f) + 0.25f * speed + 0.35f * flare + 0.15f * tremble;

		// The gown sways; its wisps undulate in waves running root to tip, trail out behind as she moves and whip
		// about in the scream.
		float whip = 1.0f + 2.0f * state.scream;
		skirt.xRot += 0.04f * Mth.sin(age * 0.07f) * alive + 0.15f * speed - 0.1f * flare;
		for (int i = 0; i < wisps.length; i++) {
			float phase = i * 1.3f;
			wisps[i].xRot += 0.12f * whip * Mth.sin(age * 0.1f + phase) + 0.5f * speed + 0.3f * flare - 0.2f * fade;
			wisps[i].zRot += WISP_SIDES[i] * (0.1f * Mth.cos(age * 0.08f + phase) - 0.12f * flare);
			wispTips[i].xRot += 0.25f * whip * Mth.sin(age * 0.1f + phase - 0.9f) + 0.3f * speed;
		}
		tail.xRot += 0.1f * whip * Mth.sin(age * 0.09f + 0.5f) + 0.4f * speed;
		tail.zRot += 0.1f * Mth.sin(age * 0.07f);
		tailMid.xRot += 0.2f * whip * Mth.sin(age * 0.09f - 0.4f) + 0.2f * speed;
		tailMid.zRot += 0.15f * Mth.sin(age * 0.07f - 0.6f);
		tailTip.xRot += 0.3f * whip * Mth.sin(age * 0.09f - 1.3f) + 0.2f * speed;
		tailTip.zRot += 0.2f * Mth.sin(age * 0.07f - 1.2f);
	}
