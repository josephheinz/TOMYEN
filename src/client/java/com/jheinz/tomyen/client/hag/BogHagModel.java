	@Override
	public void setupAnim(BogHagRenderState state) {
		super.setupAnim(state);
		float age = state.ageInTicks;
		float walk = state.walkAnimationPos;
		float speed = state.walkAnimationSpeed;
		float stride = Mth.cos(walk * 0.6f);
		float step = Mth.sin(walk * 0.6f);
		float swing = stride * 0.45f * speed;
		float bob = Math.abs(step) * speed;
		float breathe = Mth.sin(age * 0.07f);
		float menace = state.aggressive ? 1.0f : 0.0f;
		float yaw = Mth.clamp(state.yRot, -60.0f, 60.0f) * Mth.DEG_TO_RAD;

		neck.yRot += yaw * 0.4f;
		head.yRot += yaw * 0.6f;
		head.xRot += state.xRot * Mth.DEG_TO_RAD * 0.6f;

		// A hobbling shuffle: short steps, the hips rolling, the hump bobbing; the staff swings forward with her right
		// foot, the lantern arm a little, and the lantern swings on its bail behind them (below).
		hips.zRot += 0.06f * stride * speed;
		hips.y += 0.6f * bob;
		torso.xRot += 0.03f * breathe + 0.08f * bob - 0.1f * menace;
		torso.zRot -= 0.05f * stride * speed;
		rightLeg.xRot += swing;
		leftLeg.xRot -= swing;
		rightFoot.xRot -= Math.max(0.0f, swing) * 0.5f;
		leftFoot.xRot -= Math.max(0.0f, -swing) * 0.5f;
		rightArm.xRot += -0.3f * stride * speed - 0.2f * menace;
		leftArm.xRot += 0.12f * stride * speed - 0.25f * menace;
		shawl.xRot -= 0.04f * breathe;
		head.zRot += 0.04f * Mth.sin(age * 0.05f);

		float progress = state.spellProgress;
		if (state.spell == BogHag.Spell.HEX) {
			// The staff hauled up and back over her head, then thrust out at the target as the hex flies.
			float wind = progress < HEX_RELEASE ? smooth(progress / HEX_RELEASE) : 1.0f - smooth((progress - HEX_RELEASE) / (1.0f - HEX_RELEASE));
			float thrust = progress >= HEX_RELEASE ? Mth.sin(Mth.clamp((progress - HEX_RELEASE) / (1.0f - HEX_RELEASE), 0.0f, 1.0f) * Mth.PI)
					: 0.0f;
			rightArm.xRot += -1.9f * wind - 0.7f * thrust;
			rightArm.zRot += 0.35f * wind;
			rightForearm.xRot += 0.55f * wind + 0.5f * thrust;
			torso.xRot += -0.35f * wind + 0.25f * thrust;
			neck.xRot -= 0.1f * wind;
			head.xRot += -0.15f * wind + 0.1f * thrust;
			leftArm.xRot += 0.35f * wind;
			leftArm.zRot += 0.3f * wind;
		} else if (state.spell == BogHag.Spell.SUMMON) {
			// Both arms flung up, staff and lantern high, rearing back; then the staff slammed down, bent double.
			float rise = smooth(progress / SUMMON_RELEASE);
			float slam = progress >= SUMMON_RELEASE ? smooth((progress - SUMMON_RELEASE) / 0.12f) : 0.0f;
			float recover = progress >= 0.82f ? smooth((progress - 0.82f) / 0.18f) : 0.0f;
			float up = rise * (1.0f - slam);
			float down = slam * (1.0f - recover);
			rightArm.xRot += -2.2f * up - 0.15f * down;
			rightArm.zRot += 0.4f * up;
			rightForearm.xRot += 0.6f * up;
			leftArm.xRot -= 1.4f * up;
			leftArm.zRot -= 0.5f * up;
			leftForearm.xRot += 0.4f * up;
			torso.xRot += -0.45f * up + 0.2f * down;
			neck.xRot += -0.25f * up + 0.1f * down;
			head.xRot -= 0.3f * up;
			hips.y += 0.5f * down;
		}

		float attack = state.attackAnim;
		if (attack > 0.0f) {
			// A rap of the staff, swung across in front of her, low.
			float across = Mth.sin(attack * Mth.PI);
			float raise = Mth.sin(Mth.sqrt(attack) * Mth.PI);
			rightArm.xRot -= 0.9f * raise;
			rightArm.yRot += 0.7f * across;
			rightArm.zRot += 0.5f * raise;
			torso.yRot += 0.25f * across;
		}

		// The lantern hangs plumb from her hand whatever her arm does, swinging a little behind the motion.
		float chain = hips.xRot + torso.xRot + leftArm.xRot + leftForearm.xRot + leftHand.xRot;
		float lag = 0.25f * Mth.sin(walk * 0.6f - 1.0f) * speed + 0.06f * Mth.sin(age * 0.09f);
		lantern.xRot = -chain + lag;
		lantern.yRot = 0.0f;
		lantern.zRot = -leftArm.zRot + 0.05f * Mth.sin(age * 0.07f);
	}

	private static float smooth(float t) {
		float c = Mth.clamp(t, 0.0f, 1.0f);
		return c * c * (3.0f - 2.0f * c);
	}
