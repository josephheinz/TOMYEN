	@Override
	public void setupAnim(BoarRenderState state) {
		super.setupAnim(state);
		float age = state.ageInTicks;
		float speed = state.walkAnimationSpeed;
		float phase = state.walkAnimationPos * 0.6662f;
		float charge = state.charge;

		// Walking it trots (diagonal pairs); charging it bounds (the front pair together, then the back pair). Each
		// lower leg folds while its leg swings forward through the air.
		float trotA = Mth.cos(phase) * 1.2f * speed;
		float trotB = Mth.cos(phase + Mth.PI) * 1.2f * speed;
		float boundFront = Mth.cos(phase) * 1.4f * speed;
		float boundBack = Mth.cos(phase + Mth.PI) * 1.4f * speed;
		boolean bounding = charge > 0.5f;
		leg(rightFrontLeg, rightFrontShin, trotA, boundFront, charge, phase, speed);
		leg(leftFrontLeg, leftFrontShin, trotB, boundFront, charge, bounding ? phase : phase + Mth.PI, speed);
		leg(rightBackLeg, rightBackShin, trotB, boundBack, charge, phase + Mth.PI, speed);
		leg(leftBackLeg, leftBackShin, trotA, boundBack, charge, bounding ? phase + Mth.PI : phase, speed);
		body.y += Math.abs(Mth.cos(phase)) * 0.5f * speed;
		body.xRot += 0.1f * Mth.sin(phase) * charge * speed;

		head.yRot += Mth.clamp(state.yRot, -40.0f, 40.0f) * Mth.DEG_TO_RAD * 0.8f;
		head.xRot += state.xRot * Mth.DEG_TO_RAD * 0.6f + 0.06f * Mth.cos(phase * 2.0f) * speed;
		// The ears flick now and then.
		float flick = age % FLICK_PERIOD;
		if (flick < FLICK_TICKS) {
			rightEar.zRot -= 0.3f * Mth.sin(flick / FLICK_TICKS * Mth.PI);
		}
		// The tail swishes; with its hackles up the boar carries it high and stiff, and its crest rises.
		float agitated = state.agitated;
		tail.zRot += 0.3f * Mth.sin(age * 0.25f) * (1.0f - agitated);
		tail.xRot += 1.9f * agitated;
		mane.y -= 0.8f * agitated;

		float root = state.root;
		if (root > 0.0f) {
			// Snout down in the dirt, nudging and shoving, chewing at what it turns up.
			head.xRot += 0.75f * root + 0.12f * root * Mth.sin(age * 0.9f);
			head.yRot += 0.15f * root * Mth.sin(age * 0.37f);
			jaw.xRot += 0.18f * root * Math.max(0.0f, Mth.sin(age * 1.3f));
			body.xRot += 0.08f * root;
			rightFrontLeg.xRot -= 0.1f * root;
			leftFrontLeg.xRot -= 0.1f * root;
		}
		float paw = state.paw;
		if (paw > 0.0f) {
			// The warning: head low, weight back, a front hoof scraping the ground again and again.
			float cycle = age * 0.55f;
			float lift = Math.max(0.0f, Mth.sin(cycle));
			head.xRot += 0.35f * paw;
			body.xRot += 0.06f * paw;
			body.z += 0.6f * paw;
			rightFrontLeg.xRot += paw * (-0.9f * lift + 0.35f * Mth.cos(cycle));
			rightFrontShin.xRot += paw * 0.9f * lift;
			jaw.xRot += 0.12f * paw;
			rightEar.xRot -= 0.5f * paw;
			leftEar.xRot -= 0.5f * paw;
		}
		if (charge > 0.0f) {
			// Head down and level, tusks forward, ears flat.
			head.xRot += 0.4f * charge;
			body.xRot += 0.05f * charge;
			rightEar.xRot -= 0.7f * charge;
			leftEar.xRot -= 0.7f * charge;
		}
		float stun = state.stun;
		if (stun > 0.0f) {
			// Dazed: head hanging and lolling, legs splayed, body sagging.
			head.xRot += 0.5f * stun;
			head.zRot += 0.35f * stun * Mth.sin(age * 0.35f);
			head.yRot += 0.25f * stun * Mth.cos(age * 0.35f);
			body.zRot += 0.08f * stun * Mth.sin(age * 0.35f);
			body.y += 1.0f * stun;
			jaw.xRot += 0.25f * stun;
			rightFrontLeg.zRot += 0.2f * stun;
			rightBackLeg.zRot += 0.2f * stun;
			leftFrontLeg.zRot -= 0.2f * stun;
			leftBackLeg.zRot -= 0.2f * stun;
			rightEar.xRot += 0.6f * stun;
			leftEar.xRot += 0.6f * stun;
			rightEar.zRot += 0.3f * stun;
			leftEar.zRot -= 0.3f * stun;
		}
		float attack = state.attackAnim;
		if (attack > 0.0f) {
			// The gore: a short dip of the head, then a hard upward toss of the tusks.
			float dip = attack < GORE_DIP ? Mth.sin(attack / GORE_DIP * Mth.PI) : 0.0f;
			float toss = attack > GORE_DIP ? Mth.sin((attack - GORE_DIP) / (1.0f - GORE_DIP) * Mth.PI) : 0.0f;
			head.xRot += 0.4f * dip - 1.1f * toss;
			jaw.xRot += 0.3f * toss;
			rightFrontLeg.xRot -= 0.3f * toss;
			leftFrontLeg.xRot -= 0.3f * toss;
			body.xRot -= 0.06f * toss;
		}

		// Piglets: a bigger head and no tusks yet. Tuskers carry big ones; sows small ones.
		if (state.isBaby) {
			head.xScale = head.yScale = head.zScale = 1.25f;
			rightTusk.visible = false;
			leftTusk.visible = false;
		} else {
			float tusks = state.tusker ? 1.45f : 0.85f;
			rightTusk.xScale = rightTusk.yScale = rightTusk.zScale = tusks;
			leftTusk.xScale = leftTusk.yScale = leftTusk.zScale = tusks;
			rightTusk.visible = true;
			leftTusk.visible = true;
		}
	}

	private static void leg(ModelPart leg, ModelPart shin, float trot, float bound, float charge, float liftPhase, float speed) {
		leg.xRot += Mth.lerp(charge, trot, bound);
		shin.xRot += Math.max(0.0f, Mth.sin(liftPhase)) * 0.8f * speed;
	}
