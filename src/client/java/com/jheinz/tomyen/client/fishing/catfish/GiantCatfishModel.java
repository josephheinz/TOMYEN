	@Override
	public void setupAnim(GiantCatfishRenderState state) {
		super.setupAnim(state);
		float age = state.ageInTicks;
		if (state.mounted) {
			mounted();
			return;
		}
		float swim = Math.min(1.0f, state.swim);
		float tail = state.tail;
		float amp = 0.35f + 0.65f * swim;
		// The travelling wave: small at the trunk, growing to the tail; the head counters the trunk's sway.
		body.yRot += amp * 0.05f * Mth.sin(tail);
		mid.yRot += amp * 0.12f * Mth.sin(tail - 0.9f);
		tail1.yRot += amp * 0.18f * Mth.sin(tail - 1.8f);
		tail2.yRot += amp * 0.24f * Mth.sin(tail - 2.7f);
		tail3.yRot += amp * 0.28f * Mth.sin(tail - 3.5f);
		fin.yRot += amp * 0.32f * Mth.sin(tail - 4.3f);
		head.yRot += -amp * 0.04f * Mth.sin(tail) + 0.25f * Mth.clamp(state.yRot, -40.0f, 40.0f) * Mth.DEG_TO_RAD;
		if (state.beached) {
			// Beached: it bends into a C and back.
			float bend = 0.22f * Mth.sin(age * 0.5f);
			mid.yRot += bend;
			tail1.yRot += bend;
			tail2.yRot += bend;
			tail3.yRot += 0.8f * bend;
			head.yRot -= 0.6f * bend;
		}
		float slap = state.slap;
		if (slap > 0.0f) {
			// The tail slap: curls toward the side it'll strike from, whips across, and recovers.
			float wind = ramp(slap, 0.0f, 0.35f);
			float strike = ramp(slap, 0.35f, 0.55f);
			float back = ramp(slap, 0.7f, 1.0f);
			float angle = state.slapSide * (0.5f * wind - 1.4f * strike) * (1.0f - back);
			mid.yRot += 0.35f * angle;
			tail1.yRot += 0.6f * angle;
			tail2.yRot += 0.8f * angle;
			tail3.yRot += 0.6f * angle;
			fin.yRot += 0.5f * angle;
			head.yRot -= 0.3f * angle;
			body.zRot += state.slapSide * 0.18f * Mth.sin(Mth.PI * slap);
		}
		float thrash = state.thrash;
		if (thrash > 0.0f) {
			// Shaking what it's dragging (or itself, harpooned).
			body.zRot += thrash * 0.22f * Mth.sin(age * 0.9f);
			head.yRot += thrash * 0.18f * Mth.sin(age * 1.3f);
			head.xRot += thrash * 0.1f * Mth.sin(age * 1.1f);
		}
		float mouth = state.mouth;
		jaw.xRot += 0.75f * mouth;
		head.xRot -= 0.12f * mouth + 0.25f * state.roar;
		body.xRot -= 0.1f * state.roar;
		float breathe = 0.5f + 0.5f * Mth.sin(age * 0.12f);
		for (int k = 0; k < 2; k++) {
			float s = k == 0 ? -1.0f : 1.0f;
			gills[k].yRot += s * (0.12f * breathe + 0.35f * mouth);
			pectorals[k].zRot += 0.2f * Mth.sin(age * 0.2f + (k == 0 ? 0.0f : Mth.PI)) * (1.0f - 0.5f * swim) * s;
			pectorals[k].yRot += 0.35f * swim * s;
			pelvics[k].zRot += 0.12f * Mth.sin(age * 0.2f + 1.0f) * s;
			float o = k == 0 ? 0.0f : 2.1f;
			ModelPart[] whisker = barbels[k];
			whisker[0].yRot += -0.4f * s * swim + 0.10f * Mth.sin(age * 0.06f + o) - amp * 0.08f * Mth.sin(tail - 0.5f);
			whisker[0].xRot += 0.08f * Mth.sin(age * 0.05f + o) + 0.15f * swim;
			whisker[1].yRot += 0.16f * Mth.sin(age * 0.06f + o - 0.8f) - amp * 0.1f * Mth.sin(tail - 1.1f);
			whisker[1].xRot += 0.1f * Mth.sin(age * 0.05f + o - 0.8f);
			whisker[2].yRot += 0.22f * Mth.sin(age * 0.06f + o - 1.6f) - amp * 0.12f * Mth.sin(tail - 1.7f);
			whisker[2].xRot += 0.12f * Mth.sin(age * 0.05f + o - 1.6f);
			nasals[k].xRot += 0.06f * Mth.sin(age * 0.1f + o);
			for (int c = 0; c < 2; c++) {
				chins[k][c].xRot += 0.12f * Mth.sin(age * 0.09f + c + o) + 0.35f * swim;
			}
		}
		dorsal.xRot += 0.25f * state.roar;
		rope.xRot += 0.1f * Mth.sin(age * 0.08f);
		rope.zRot += 0.1f * Mth.sin(age * 0.06f);
	}

	/** On a Giant Fish Mount: an S through the body, the mouth open, fins spread, whiskers out. */
	private void mounted() {
		body.yRot += 0.03f;
		mid.yRot += 0.08f;
		tail1.yRot += 0.14f;
		tail2.yRot += 0.18f;
		tail3.yRot += 0.12f;
		fin.yRot += 0.1f;
		head.yRot -= 0.1f;
		head.xRot -= 0.06f;
		jaw.xRot += 0.5f;
		for (int k = 0; k < 2; k++) {
			float s = k == 0 ? -1.0f : 1.0f;
			gills[k].yRot += 0.22f * s;
			pectorals[k].zRot += 0.25f * s;
			pectorals[k].yRot += 0.15f * s;
			barbels[k][0].yRot -= 0.1f * s;
			barbels[k][0].xRot += 0.12f;
			barbels[k][1].yRot += 0.12f * s;
			barbels[k][1].xRot += 0.08f;
			barbels[k][2].yRot += 0.2f * s;
			barbels[k][2].xRot += 0.06f;
		}
		dorsal.xRot += 0.15f;
	}

	/** 0 before a, 1 after b, smooth between. */
	private static float ramp(float value, float a, float b) {
		float t = Mth.clamp((value - a) / (b - a), 0.0f, 1.0f);
		return t * t * (3.0f - 2.0f * t);
	}
