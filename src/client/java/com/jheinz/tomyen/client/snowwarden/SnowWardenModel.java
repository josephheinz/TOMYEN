	private static float smooth(float t) {
		t = Mth.clamp(t, 0.0f, 1.0f);
		return t * t * (3.0f - 2.0f * t);
	}

	/** A fist swung overhead and down, p 0..1: {the arm's turn, the body's twist into it, its lean}. */
	static float[] swingCurve(float p) {
		if (p <= 0.0f || p >= 1.0f) {
			return new float[] {0.0f, 0.0f, 0.0f};
		}
		if (p < 0.4f) {
			float k = smooth(p / 0.4f);
			return new float[] {-2.3f * k, -0.3f * k, -0.08f * k};
		}
		if (p < 0.6f) {
			float k = (p - 0.4f) / 0.2f;
			return new float[] {-2.3f + 2.8f * k * k, -0.3f + 0.6f * k, -0.08f + 0.3f * k};
		}
		float k = smooth((p - 0.6f) / 0.4f);
		return new float[] {0.5f * (1.0f - k), 0.3f * (1.0f - k), 0.22f * (1.0f - k)};
	}

	/** Both fists raised high and slammed down, p 0..1: {the arms' turn, the body's lean}. */
	static float[] slamCurve(float p) {
		if (p <= 0.0f || p >= 1.0f) {
			return new float[] {0.0f, 0.0f};
		}
		if (p < 0.5f) {
			float k = smooth(p / 0.5f);
			return new float[] {-2.9f * k, -0.2f * k};
		}
		if (p < 0.6f) {
			float k = (p - 0.5f) / 0.1f;
			return new float[] {-2.9f + 2.6f * k * k, -0.2f + 0.65f * k};
		}
		float k = smooth((p - 0.6f) / 0.4f);
		return new float[] {-0.3f * (1.0f - k), 0.45f * (1.0f - k)};
	}

	/** An arm wound back and a snowball lobbed, p 0..1: {the arm's turn, the body's twist, its lean}. */
	static float[] throwCurve(float p) {
		if (p <= 0.0f || p >= 1.0f) {
			return new float[] {0.0f, 0.0f, 0.0f};
		}
		if (p < 0.55f) {
			float k = smooth(p / 0.55f);
			return new float[] {-2.6f * k, -0.35f * k, -0.1f * k};
		}
		if (p < 0.7f) {
			float k = (p - 0.55f) / 0.15f;
			return new float[] {-2.6f + 2.0f * k, -0.35f + 0.65f * k, -0.1f + 0.3f * k};
		}
		float k = smooth((p - 0.7f) / 0.3f);
		return new float[] {-0.6f * (1.0f - k), 0.3f * (1.0f - k), 0.2f * (1.0f - k)};
	}

	/** The chest thrown forward as the frost blast fires, b 0..1 through the blast. */
	static float blastThrust(float b) {
		if (b <= 0.0f || b >= 1.0f) {
			return 0.0f;
		}
		return b < 0.2f ? b / 0.2f : 1.0f - smooth((b - 0.2f) / 0.8f);
	}

	static float roarEnvelope(float r) {
		if (r <= 0.0f || r >= 1.0f) {
			return 0.0f;
		}
		return smooth(r / 0.2f) * (1.0f - smooth((r - 0.8f) / 0.2f));
	}

	/** The pose on top of the rest pose (see tools/gen_snow_warden.py's twin). */
	private void pose(SnowWardenRenderState state) {
		float amp = Math.min(1.0f, state.walkAnimationSpeed);
		float stride = state.walkAnimationPos * 0.5f;
		float s = Mth.sin(stride);
		float c = Mth.cos(stride);
		float age = state.ageInTicks;
		float breathe = Mth.sin(age * 0.06f);
		float[] swing = swingCurve(state.swing);
		float[] slam = slamCurve(state.slam);
		float[] toss = throwCurve(state.throwing);
		float thrust = blastThrust(state.blast);
		float howl = roarEnvelope(state.roar);
		float charge = state.charge;
		float sniff = state.sniff;

		// Short, heavy steps: the body bobs and sways with them.
		body.y += Math.abs(s) * 0.8f * amp;
		body.xRot += 0.015f * breathe + swing[2] + slam[1] + toss[2] - 0.22f * charge + 0.3f * thrust - 0.18f * howl + 0.1f * sniff;
		body.yRot += 0.05f * s * amp + (state.swingLeft ? -swing[1] : swing[1]) + toss[1];
		body.zRot += 0.05f * s * amp;

		rightLeg.xRot += c * 0.55f * amp;
		leftLeg.xRot -= c * 0.55f * amp;

		// The arms: swinging with the stride, hanging a little out; raised for the blows; spread to charge and roar.
		float spread = 0.7f * charge + 0.9f * howl + 0.03f * breathe;
		float lift = slam[0] + 0.35f * charge - 0.5f * howl;
		float inward = 0.25f * slam[0] / 2.9f;
		rightArm.xRot += -c * 0.4f * amp + lift;
		leftArm.xRot += c * 0.4f * amp + lift;
		rightArm.zRot += spread + inward;
		leftArm.zRot -= spread + inward;
		(state.swingLeft ? leftArm : rightArm).xRot += swing[0];
		rightArm.xRot += toss[0];

		// The head: looking about, thrown back to roar (shaking), tipped down and turning to sniff, up as it charges.
		float yaw = state.yRot * Mth.DEG_TO_RAD;
		float pitch = state.xRot * Mth.DEG_TO_RAD;
		head.xRot += 0.7f * pitch - 0.3f * charge - 0.55f * howl + 0.35f * sniff;
		head.yRot += 0.8f * yaw + 0.45f * Mth.sin(age * 0.25f) * sniff;
		head.zRot += 0.08f * Mth.sin(age * 1.3f) * howl;
		// The tendrils quiver, and flare out when it roars, sniffs or charges.
		float flare = 0.5f * howl + 0.3f * sniff + 0.25f * charge;
		rightTendril.zRot -= 0.08f * Mth.sin(age * 0.15f) + flare;
		leftTendril.zRot += 0.08f * Mth.sin(age * 0.15f + 1.7f) + flare;
	}
