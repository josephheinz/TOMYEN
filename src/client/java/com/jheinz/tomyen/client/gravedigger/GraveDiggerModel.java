	@Override
	public void setupAnim(GraveDiggerRenderState state) {
		super.setupAnim(state);
		float age = state.ageInTicks;
		float walk = state.walkAnimationPos;
		float speed = state.walkAnimationSpeed;
		float stride = Mth.cos(walk * 0.6662f);
		float hunt = state.aggressive ? 1.0f : 0.0f;

		head.yRot += Mth.clamp(state.yRot, -60.0f, 60.0f) * Mth.DEG_TO_RAD;
		head.xRot += state.xRot * Mth.DEG_TO_RAD * 0.7f;

		// A shambling, dragging walk: the right leg takes the full stride, the left a shorter one; each knee folds as
		// its leg swings through. He sways and bobs; hunting, he hunches lower.
		float rightLegRot = stride * 0.9f * speed;
		float leftLegRot = -stride * 0.6f * speed;
		rightLeg.xRot += rightLegRot;
		leftLeg.xRot += leftLegRot;
		rightShin.xRot += Math.max(0.0f, -rightLegRot) * 1.1f;
		leftShin.xRot += Math.max(0.0f, -leftLegRot) * 1.1f;
		body.zRot += 0.07f * stride * speed;
		body.xRot += 0.08f * hunt;
		body.y += Math.abs(Mth.sin(walk * 0.6662f)) * 0.8f * speed;
		// His head lolls; the jaw works slowly, and hangs wider when he's after someone.
		head.zRot += 0.05f * Mth.sin(age * 0.045f);
		head.xRot -= 0.08f * hunt;
		jaw.xRot += 0.12f * Math.max(0.0f, Mth.sin(age * 0.07f)) + 0.12f * hunt;
		// The coat's flaps follow the legs forward; the back panel kicks out behind.
		coatRight.xRot += Math.min(0.0f, rightLegRot) * 0.9f;
		coatLeft.xRot += Math.min(0.0f, leftLegRot) * 0.9f;
		coatBack.xRot += Math.max(0.0f, Math.max(rightLegRot, leftLegRot)) * 0.5f + 0.12f * speed;
		// The lantern swings.
		lantern.xRot += -0.3f * Mth.sin(walk * 0.6662f) * speed + 0.04f * Mth.sin(age * 0.09f);
		lantern.zRot += -0.1f * stride * speed;
		// The left arm reaches out and gropes; the right carries the shovel on his shoulder, bobbing with his step.
		leftArm.xRot += 0.12f * stride * speed + 0.06f * Mth.sin(age * 0.067f) - 0.25f * hunt;
		leftForearm.xRot += -0.1f * Mth.sin(age * 0.067f + 1.0f);
		rightArm.xRot += -0.06f * stride * speed;

		float attack = state.attackAnim;
		if (attack > 0.0f) {
			// An overhead chop: the shovel hauled up off the shoulder and back over his head, then brought down hard in
			// front of him, blade first, his whole back bending into it; then back onto the shoulder. Each arm part
			// blends toward its wound-up pose, then toward its struck one.
			float wind;
			float strike;
			if (attack < 0.3f) {
				wind = attack / 0.3f;
				strike = 0.0f;
			} else if (attack < 0.55f) {
				strike = (attack - 0.3f) / 0.25f;
				wind = 1.0f - strike;
			} else {
				wind = 0.0f;
				strike = 1.0f - (attack - 0.55f) / 0.45f;
			}
			chop(rightArm, wind, -2.9f, 0.0f, 0.25f, strike, -1.3f, 0.0f, 0.1f);
			chop(rightForearm, wind, -0.45f, 0.0f, 0.0f, strike, -0.15f, 0.0f, 0.0f);
			chop(shovel, wind, 0.7f, 0.0f, 0.0f, strike, 1.55f, 0.0f, 0.0f);
			chop(leftArm, wind, -2.6f, 0.0f, -0.45f, strike, -0.95f, 0.0f, -0.3f);
			chop(leftForearm, wind, -0.5f, 0.0f, 0.0f, strike, -0.3f, 0.0f, 0.0f);
			body.xRot += -0.15f * wind + 0.3f * strike;
			head.xRot += 0.1f * wind - 0.2f * strike;
			jaw.xRot += 0.4f * wind;
		}

		GraveDigger.DigMode dig = state.dig;
		if (dig != GraveDigger.DigMode.NONE) {
			// Digging: both hands on the shaft, stabbing the blade in and levering it back, over and over.
			float cycle = Mth.sin(age * 0.5f);
			float stab = Math.max(0.0f, cycle);
			float lever = Math.max(0.0f, -cycle);
			float aimArm = switch (dig) {
				case DOWN -> -0.55f;
				case FORWARD -> -1.35f;
				default -> -2.6f;
			};
			float aimBody = switch (dig) {
				case DOWN -> 0.55f;
				case FORWARD -> 0.05f;
				default -> -0.3f;
			};
			rightArm.setRotation(aimArm + 0.35f * stab - 0.25f * lever, 0.0f, 0.15f);
			rightForearm.setRotation(-0.35f - 0.3f * lever, 0.0f, 0.0f);
			shovel.setRotation(1.25f + 0.2f * lever, 0.0f, 0.0f);
			leftArm.setRotation(aimArm + 0.25f + 0.3f * stab - 0.2f * lever, 0.0f, -0.35f);
			leftForearm.setRotation(-0.6f, 0.0f, 0.0f);
			body.xRot += aimBody * 0.4f + 0.1f * stab;
			head.xRot -= aimBody * 0.3f;
		}
	}

	/** Blends a part's rotation toward the wound-up pose by {@code wind}, then toward the struck pose by {@code strike}. */
	private static void chop(ModelPart part, float wind, float wx, float wy, float wz, float strike, float sx, float sy, float sz) {
		part.xRot = Mth.lerp(strike, Mth.lerp(wind, part.xRot, wx), sx);
		part.yRot = Mth.lerp(strike, Mth.lerp(wind, part.yRot, wy), sy);
		part.zRot = Mth.lerp(strike, Mth.lerp(wind, part.zRot, wz), sz);
	}
