	@Override
	public void setupAnim(WerewolfRenderState state) {
		super.setupAnim(state);
		float age = state.ageInTicks;
		float walk = state.walkAnimationPos;
		float speed = state.walkAnimationSpeed;
		float stride = Mth.cos(walk * 0.5f);
		float swing = stride * 0.8f * speed;
		float bob = Math.abs(Mth.sin(walk * 0.5f)) * speed;
		float hunt = state.aggressive ? 1.0f : 0.0f;

		neck.yRot += Mth.clamp(state.yRot, -60.0f, 60.0f) * Mth.DEG_TO_RAD * 0.4f;
		head.yRot += Mth.clamp(state.yRot, -60.0f, 60.0f) * Mth.DEG_TO_RAD * 0.6f;
		head.xRot += state.xRot * Mth.DEG_TO_RAD * 0.5f;

		// A heavy, rolling gait: the hips dip and sway, the shoulders roll against them, each knee folds as its leg
		// swings back, the arms swing against the legs. Hunting, it drops lower, arms spread and claws out.
		body.y += 1.2f * bob + 2.0f * hunt;
		body.zRot += 0.08f * stride * speed;
		chest.zRot -= 0.12f * stride * speed;
		chest.xRot += 0.2f * hunt;
		neck.xRot -= 0.3f * hunt;
		rightLeg.y += 2.0f * hunt;
		leftLeg.y += 2.0f * hunt;
		rightLeg.xRot += swing - 0.3f * hunt;
		leftLeg.xRot += -swing - 0.3f * hunt;
		rightShin.xRot += Math.max(0.0f, -stride) * 0.6f * speed + 0.45f * hunt;
		leftShin.xRot += Math.max(0.0f, stride) * 0.6f * speed + 0.45f * hunt;
		rightHock.xRot -= 0.15f * hunt;
		leftHock.xRot -= 0.15f * hunt;
		rightArm.xRot += -swing - 0.55f * hunt;
		leftArm.xRot += swing - 0.55f * hunt;
		rightArm.zRot -= 0.5f * hunt;
		leftArm.zRot += 0.5f * hunt;
		rightForearm.xRot -= Math.max(0.0f, stride) * 0.4f * speed + 0.35f * hunt;
		leftForearm.xRot -= Math.max(0.0f, -stride) * 0.4f * speed + 0.35f * hunt;
		rightEar.xRot += 0.3f * hunt;
		leftEar.xRot += 0.3f * hunt;
		jaw.xRot += 0.15f * hunt;

		// The tail sways, and stiffens up as it runs or hunts.
		tail.xRot += 0.08f * Mth.sin(age * 0.08f) + 0.3f * speed + 0.4f * hunt;
		tail.yRot += 0.2f * Mth.sin(age * 0.06f);

		// Now and then the head twitches, an ear with it.
		float phase = age % TWITCH_PERIOD;
		if (phase < TWITCH_TICKS) {
			float twitch = Mth.sin(phase / TWITCH_TICKS * Mth.PI);
			head.zRot += 0.3f * twitch * Mth.sin(age * 2.3f);
			head.yRot += 0.2f * twitch * Mth.cos(age * 1.7f);
			rightEar.zRot += 0.3f * twitch;
		}

		float attack = state.attackAnim;
		if (attack > 0.0f) {
			// A claw swipe: the arm hauled up and back, then raked down and across as it lunges; the jaw gapes on the
			// wind-up and snaps shut on the rake.
			float rake = Mth.sin(attack * Mth.PI);
			float raise = Mth.sin(Mth.sqrt(attack) * Mth.PI);
			ModelPart arm = state.leftSwipe ? leftArm : rightArm;
			ModelPart forearm = state.leftSwipe ? leftForearm : rightForearm;
			float side = state.leftSwipe ? -1.0f : 1.0f;
			arm.xRot += -2.4f * raise + 0.9f * rake;
			arm.yRot += 0.5f * rake * side;
			arm.zRot += 0.5f * raise * side;
			forearm.xRot -= 0.6f * raise;
			chest.xRot += 0.25f * rake;
			neck.xRot += 0.2f * rake;
			jaw.xRot += 0.9f * snap(attack);
		}

		float howl = state.howl;
		if (howl > 0.0f) {
			// Rearing right back, head thrown up, jaw wide, arms flung out.
			body.xRot -= 0.5f * howl;
			body.y -= 1.0f * howl;
			chest.xRot -= 0.45f * howl;
			neck.xRot -= 0.55f * howl;
			head.xRot -= 0.65f * howl;
			head.yRot *= 1.0f - howl;
			jaw.xRot += 0.85f * howl;
			rightArm.xRot -= 0.5f * howl;
			leftArm.xRot -= 0.5f * howl;
			rightArm.zRot += 0.9f * howl;
			leftArm.zRot -= 0.9f * howl;
			rightForearm.xRot -= 0.5f * howl;
			leftForearm.xRot -= 0.5f * howl;
			rightEar.xRot += 0.4f * howl;
			leftEar.xRot += 0.4f * howl;
			rightLeg.xRot += 0.25f * howl;
			leftLeg.xRot += 0.25f * howl;
			rightShin.xRot -= 0.2f * howl;
			leftShin.xRot -= 0.2f * howl;
			tail.xRot -= 0.3f * howl;
		}
	}

	/** How far the jaw gapes through a swipe: wide as the arm winds up, snapped shut as it rakes down. */
	private static float snap(float attack) {
		return attack < 0.45f ? attack / 0.45f : Math.max(0.0f, 1.0f - (attack - 0.45f) / 0.15f);
	}

	/** Which arm a swipe uses: they alternate, by when the swipe began. */
	static boolean leftSwipe(float ageInTicks, float attackAnim) {
		int start = Mth.floor((ageInTicks - attackAnim * SWING_TICKS) / SWIPE_ALTERNATION);
		return (start & 1) == 1;
	}
