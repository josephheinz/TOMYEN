	/** The pose on top of the rest pose (see tools/gen_crow.py's twin). */
	private void pose(CrowRenderState state) {
		float f = state.fly;
		float tuck = Mth.clamp((f - 0.4f) / 0.6f, 0.0f, 1.0f);
		float amp = 0.25f + 0.75f * state.flapStrength;
		float beat = Mth.sin(state.flap);
		float lag = Mth.sin(state.flap - 0.8f);
		float pk = Mth.sin(state.peck * Mth.PI);
		float cw = Mth.sin(state.caw * Mth.PI);
		float age = state.ageInTicks;
		// The body levels out in flight (nose up climbing, down diving), bows to peck and to caw.
		body.xRot = Mth.lerp(f, -0.35f, 0.05f) + state.flightPitch * f + 0.55f * pk + 0.18f * cw;
		body.y += 0.25f * Mth.sin(age * 0.08f) * (1.0f - f);
		head.xRot = Mth.lerp(f, 0.3f, -0.05f) + state.xRot * Mth.DEG_TO_RAD + 0.6f * pk - 0.42f * cw;
		head.yRot = state.yRot * Mth.DEG_TO_RAD;
		jaw.xRot = 0.55f * cw + 0.12f * pk;
		if (state.sleeping) {
			head.xRot += 0.45f;
			head.y += 1.0f;
			head.z += 1.0f;
			body.y += 0.5f;
		}
		// The tail lifts level in flight and fans out; it flicks up on a caw and twitches now and then at rest.
		tail.xRot += -0.25f * f - 0.35f * cw;
		tail.yRot = 0.06f * Mth.sin(age * 0.11f) * (1.0f - f);
		tailLeft.yRot = Mth.lerp(f, -0.2f, 0.35f);
		tailRight.yRot = Mth.lerp(f, 0.2f, -0.35f);
		// Wings: from folded along the flanks to spread and beating about the body's long axis, the hand lagging.
		float spread = 1.0f - f;
		float stroke = f * (0.1f + 0.65f * amp * beat);
		rightWing.setRotation(0.0f, FOLD_Y * spread, FOLD_Z * spread + stroke - 0.12f * cw * spread);
		leftWing.setRotation(0.0f, -FOLD_Y * spread, -FOLD_Z * spread - stroke + 0.12f * cw * spread);
		rightHand.setRotation(0.0f, 0.18f * f, f * 0.4f * amp * lag);
		leftHand.setRotation(0.0f, -0.18f * f, -f * 0.4f * amp * lag);
		// The fingers close into one point folded, and fan apart in flight.
		float front = Mth.lerp(f, 0.25f, -0.12f);
		float back = Mth.lerp(f, -0.25f, 0.12f);
		fingers[0].yRot = front;
		fingers[2].yRot = back;
		fingers[3].yRot = -front;
		fingers[5].yRot = -back;
		// Legs tuck back in flight, toes curled.
		rightLeg.xRot = 1.25f * tuck;
		leftLeg.xRot = 1.25f * tuck;
		rightFoot.xRot = 0.8f * tuck;
		leftFoot.xRot = 0.8f * tuck;
	}
