	@Override
	public void setupAnim(ScarecrowRenderState state) {
		super.setupAnim(state);
		pose(this, state);
		strawHat.visible = !state.hatOff;
		nose.visible = state.variant != Scarecrow.Variant.PUMPKIN;
	}

	/**
	 * Its pose: head lolling to one side and nodding in the wind, arms out along the crossbar with the sleeves
	 * fluttering, legs dangling and swinging a little, all sagging as it's battered and thrashing up a tractor beam.
	 * Shared with {@link ScarecrowArmorModel}.
	 */
	static void pose(HumanoidModel<?> model, ScarecrowRenderState state) {
		float t = state.ageInTicks + state.phase;
		float wind = state.wind;
		float flail = state.lifted ? 1.0f : 0.0f;
		float tatter = state.tatter;
		model.head.xRot = 0.08f + 0.05f * Mth.sin(t * 0.051f) * wind + 0.25f * tatter;
		model.head.yRot = 0.06f * Mth.sin(t * 0.023f);
		model.head.zRot = 0.14f + 0.06f * Mth.sin(t * 0.043f + 0.7f) * wind + 0.2f * tatter;
		model.body.xRot = 0.0f;
		model.body.yRot = 0.0f;
		model.body.zRot = 0.0f;
		float reach = Mth.HALF_PI - 0.06f - 0.22f * tatter;
		model.rightArm.xRot = 0.04f * Mth.sin(t * 0.09f) * wind;
		model.rightArm.yRot = 0.0f;
		model.rightArm.zRot = reach + 0.03f * Mth.sin(t * 0.13f) * wind + 0.35f * flail * Mth.sin(t * 0.55f);
		model.leftArm.xRot = 0.04f * Mth.sin(t * 0.09f + 1.9f) * wind;
		model.leftArm.yRot = 0.0f;
		model.leftArm.zRot = -reach - 0.03f * Mth.sin(t * 0.13f + 2.4f) * wind - 0.35f * flail * Mth.sin(t * 0.55f + 1.0f);
		model.rightLeg.xRot = -0.10f + 0.07f * Mth.sin(t * 0.071f) * wind + 0.5f * flail * Mth.sin(t * 0.6f);
		model.rightLeg.yRot = 0.0f;
		model.rightLeg.zRot = 0.07f;
		model.leftLeg.xRot = 0.06f + 0.07f * Mth.sin(t * 0.071f + 2.1f) * wind - 0.5f * flail * Mth.sin(t * 0.6f);
		model.leftLeg.yRot = 0.0f;
		model.leftLeg.zRot = -0.07f;
	}
