	/** The body's rear through a stomp, s 0..1: up onto the hind legs (to 0.45), slammed down (by 0.6), settled. */
	static float stompRear(float s) {
		if (s <= 0.0f || s >= 1.0f) {
			return 0.0f;
		}
		if (s < 0.45f) {
			return REAR_MAX * smooth(s / 0.45f);
		}
		if (s < 0.6f) {
			float k = (s - 0.45f) / 0.15f;
			return REAR_MAX + (0.07f - REAR_MAX) * k * k;
		}
		return 0.07f * (1.0f - smooth((s - 0.6f) / 0.4f));
	}

	private static float smooth(float t) {
		t = Mth.clamp(t, 0.0f, 1.0f);
		return t * t * (3.0f - 2.0f * t);
	}

	/** The pose on top of the rest pose (see tools/gen_moose.py's twin). */
	private void pose(MooseRenderState state) {
		float amp = Math.min(1.0f, state.walkAnimationSpeed);
		float stride = state.walkAnimationPos * 0.55f;
		float s = Mth.sin(stride);
		float c = Mth.cos(stride);
		float age = state.ageInTicks;
		float browse = state.browse;
		float windup = state.windup;
		float charge = state.charge;
		float swing = (0.5f + 0.3f * charge) * amp;
		float flex = (0.75f + 0.35f * charge) * amp;
		float rear = stompRear(state.stomp);
		float up = Mth.clamp(rear / REAR_MAX, 0.0f, 1.0f);
		float agitated = Math.max(Math.max(windup, charge), up);
		float paw = Mth.sin(state.pawClock * 0.45f);

		// The body: a gentle lift on each step, dipping toward the front when it lowers its head to charge, and rearing
		// up about the hips to stomp.
		float tilt = rear + 0.05f * windup + 0.04f * charge;
		body.y -= Math.abs(s) * 0.5f * amp;
		body.xRot = tilt;

		// The front legs hang from the shoulders wherever the body has put them.
		float dy = FRONT_PIVOT_Y - BODY_PIVOT_Y;
		float dz = FRONT_PIVOT_Z - BODY_PIVOT_Z;
		float legY = body.y + dy * Mth.cos(tilt) - dz * Mth.sin(tilt);
		float legZ = body.z + dy * Mth.sin(tilt) + dz * Mth.cos(tilt);
		rightFrontLeg.y = legY;
		rightFrontLeg.z = legZ;
		leftFrontLeg.y = legY;
		leftFrontLeg.z = legZ;

		// The walk: diagonal pairs, long and loping; each lower leg folds as it swings forward. A gallop when charging.
		rightFrontLeg.xRot += c * swing;
		leftFrontLeg.xRot -= c * swing;
		rightHindLeg.xRot -= c * swing;
		leftHindLeg.xRot += c * swing;
		rightFrontShin.xRot += Math.max(0.0f, s) * flex;
		leftFrontShin.xRot += Math.max(0.0f, -s) * flex;
		rightHindShin.xRot += Math.max(0.0f, -s) * flex * 0.7f;
		leftHindShin.xRot += Math.max(0.0f, s) * flex * 0.7f;
		// Pawing the ground before a charge: the right forehoof lifted forward, struck down and dragged back.
		rightFrontLeg.xRot += windup * (-0.3f + 0.4f * paw);
		rightFrontShin.xRot += windup * (0.2f + 0.7f * Math.max(0.0f, -paw));
		// Rearing: both forelegs follow the body up, folded at the knee, the left a beat behind; then thrown down straight.
		float rightUp = up;
		float leftUp = Mth.clamp(up - 0.12f, 0.0f, 1.0f) / (1.0f - 0.12f);
		rightFrontLeg.xRot += rear - 0.95f * rightUp;
		rightFrontShin.xRot += 1.45f * rightUp;
		leftFrontLeg.xRot += rear - 0.95f * leftUp;
		leftFrontShin.xRot += 1.45f * leftUp;
		rightHindLeg.xRot -= 0.18f * up;
		leftHindLeg.xRot -= 0.18f * up;
		rightHindShin.xRot += 0.2f * up;
		leftHindShin.xRot += 0.2f * up;

		// The head: nodding with the stride, looking about, stretched up high to browse, dropped low with the antlers
		// levelled to charge, tucked in as it rears.
		float yaw = state.yRot * Mth.DEG_TO_RAD;
		float pitch = state.xRot * Mth.DEG_TO_RAD;
		neck.xRot += 0.35f * pitch + 0.05f * Mth.sin(stride * 2.0f) * amp - 0.9f * browse + 0.35f * windup + 0.3f * charge + 0.25f * up;
		neck.yRot = 0.45f * yaw;
		head.xRot += 0.45f * pitch - 0.45f * browse + 0.5f * windup + 0.45f * charge - 0.15f * up;
		head.yRot = 0.4f * yaw;
		float tiltChange = (neck.xRot - NECK_REST) + (head.xRot - HEAD_REST);
		// Chewing while it browses.
		jaw.xRot = browse * (0.06f + 0.14f * Math.max(0.0f, Mth.sin(age * 0.8f)));
		// Ears: a twitch now and then; pinned back when it's angry.
		float rightTwitch = (float) Math.pow(Math.max(0.0f, Mth.sin(age * 0.11f)), 8);
		float leftTwitch = (float) Math.pow(Math.max(0.0f, Mth.sin(age * 0.11f + 2.0f)), 8);
		rightEar.xRot += -0.55f * agitated + 0.25f * browse;
		leftEar.xRot += -0.55f * agitated + 0.25f * browse;
		rightEar.zRot += 0.25f * rightTwitch - 0.2f * agitated;
		leftEar.zRot -= 0.25f * leftTwitch - 0.2f * agitated;
		// The bell hangs straight down whatever the head does, and swings with the stride.
		bell.xRot = BELL_REST - tiltChange - rear + 0.2f * s * amp + 0.05f * Mth.sin(age * 0.09f);
		bell.zRot = 0.1f * c * amp;
		bellTip.xRot = 0.15f * Mth.sin(stride - 0.8f) * amp + 0.04f * Mth.sin(age * 0.09f - 0.6f);
		// The tail flicks; it goes up when the moose is angry.
		tail.xRot += -0.7f * agitated;
		tail.zRot = 0.2f * Mth.sin(age * 0.13f) * (1.0f - 0.5f * agitated);
		// The rack (a bull's) grows back from nubs after it's shed; a calf's head is big for its body.
		boolean rack = state.bull && state.antlers > 0.0f;
		rightAntler.visible = rack;
		leftAntler.visible = rack;
		float growth = 0.25f + 0.75f * Mth.clamp(state.antlers, 0.0f, 1.0f);
		rightAntler.xScale = rightAntler.yScale = rightAntler.zScale = growth;
		leftAntler.xScale = leftAntler.yScale = leftAntler.zScale = growth;
		if (state.isBaby) {
			head.xScale = head.yScale = head.zScale = 1.3f;
		}
		saddle.visible = state.saddled;
	}
