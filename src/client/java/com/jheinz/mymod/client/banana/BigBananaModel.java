	@Override
	public void setupAnim(BigBananaRenderState state) {
		super.setupAnim(state);
		float age = state.ageInTicks;
		float speed = state.walkAnimationSpeed;
		float step = state.walkAnimationPos * WALK_RATE;
		float stride = Mth.cos(step);
		float hop = Math.abs(Mth.sin(step));

		// A bouncy waddle: short legs swinging, the body dropping onto each footfall and rocking side to side, the
		// sway rippling up the banana a beat behind; the arms swing against the legs and flap out on each step. Idle,
		// it sways and bends gently.
		rightLeg.xRot += stride * 0.9f * speed;
		leftLeg.xRot -= stride * 0.9f * speed;
		body.y += (1.0f - hop) * 1.2f * speed;
		body.zRot += 0.1f * stride * speed;
		for (int i = 0; i < SEGMENTS; i++) {
			segments[i].zRot += 0.035f * speed * Mth.sin(step - i * 0.45f) + 0.012f * Mth.sin(age * 0.07f - i * 0.4f);
			segments[i].xRot += 0.01f * Mth.sin(age * 0.05f - i * 0.3f);
		}
		rightArm.xRot -= stride * 0.6f * speed;
		leftArm.xRot += stride * 0.6f * speed;
		float flap = 0.2f * hop * speed + 0.04f * Mth.sin(age * 0.07f);
		rightArm.zRot += flap;
		leftArm.zRot -= flap;

		// It looks with its face segment (everything above turns with it) and a little with the one under.
		float yaw = Mth.clamp(state.yRot, -50.0f, 50.0f) * Mth.DEG_TO_RAD;
		segments[FACE - 1].yRot += yaw * 0.3f;
		segments[FACE].yRot += yaw * 0.5f;
		segments[FACE].xRot += state.xRot * Mth.DEG_TO_RAD * 0.3f;

		float attack = state.attackAnim;
		if (attack > 0.0f) {
			// The slap: the right arm up and out to the side, then whipped across the front, the body twisting back
			// on the wind-up and into the swing.
			float up = windUp(attack);
			float across = across(attack);
			rightArm.zRot += 2.0f * up;
			rightArm.xRot -= 1.4f * across;
			rightArm.yRot -= 0.7f * across;
			rightForearm.xRot += 0.35f * Math.max(up, across);
			float twist = 0.08f * up - 0.14f * across;
			for (int i = 1; i <= FACE; i++) {
				segments[i].yRot += twist;
			}
			segments[2].xRot += 0.1f * across;
		}

		float happy = state.happy;
		if (happy > 0.0f) {
			// Arms flung up, a wiggle up the banana, and a squash on take-off.
			float h = Mth.sin(happy * Mth.PI);
			rightArm.zRot += 2.3f * h;
			leftArm.zRot -= 2.3f * h;
			rightForearm.xRot += 0.35f * h;
			leftForearm.xRot += 0.35f * h;
			for (int i = 0; i < SEGMENTS; i++) {
				segments[i].zRot += 0.07f * h * Mth.sin(age * 0.9f - i * 0.7f);
			}
			if (happy < 0.25f) {
				body.y += 1.5f * Mth.sin(happy / 0.25f * Mth.PI);
			}
		}
	}

	/** Through a slap, how far the arm is up and out: all the way by 0.4, back down by 0.6. */
	private static float windUp(float attack) {
		return smooth(attack < 0.4f ? attack / 0.4f : 1.0f - (attack - 0.4f) / 0.2f);
	}

	/** Through a slap, how far the arm has swept across the front: from 0.35 to 0.6, then easing back. */
	private static float across(float attack) {
		return smooth(attack < 0.35f ? 0.0f : attack < 0.6f ? (attack - 0.35f) / 0.25f : 1.0f - (attack - 0.6f) / 0.4f);
	}

	private static float smooth(float t) {
		t = Mth.clamp(t, 0.0f, 1.0f);
		return t * t * (3.0f - 2.0f * t);
	}
