	public BigBananaModel(ModelPart root) {
		super(root);
		body = root.getChild("body");
		ModelPart part = body;
		for (int i = 0; i < SEGMENTS; i++) {
			part = part.getChild("segment_" + i);
			segments[i] = part;
		}
		rightArm = segments[3].getChild("right_arm");
		leftArm = segments[3].getChild("left_arm");
		rightForearm = rightArm.getChild("right_forearm");
		leftForearm = leftArm.getChild("left_forearm");
		rightLeg = root.getChild("right_leg");
		leftLeg = root.getChild("left_leg");
	}

